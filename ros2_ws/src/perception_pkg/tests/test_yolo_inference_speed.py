# FPS threshold: acceptance requires average ≥ 3 Hz on CPU.
_MIN_FPS = 3.0

# How many frames to process per test (0 = all frames in the video).
_MAX_FRAMES_PER_TEST = 120


def _video_path(name: str) -> Path:
    p = _VIDEOS_DIR / name
    if not p.exists():
        pytest.skip(f"Video not found: {p}")
    return p


def _open_video(p: Path):
    import cv2
    cap = cv2.VideoCapture(str(p))
    if not cap.isOpened():
        pytest.skip(f"Cannot open video: {p}")
    return cap


