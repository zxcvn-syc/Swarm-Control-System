# 10. Confidence range [0, 1]
# ---------------------------------------------------------------------------

def test_confidence_in_valid_range(runner):
    """confidence (detection score) must be in [0.0, 1.0]."""
    video = _open_video(_synthetic_multi())
    violations: list[tuple] = []

    try:
        for _ in range(_MAX_FRAMES_PER_TEST):
            ok, frame = video.read()
            if not ok:
                break
            records = runner.step_records(frame)
            for rec in records:
                conf = getattr(rec, "confidence", getattr(rec, "score", None))
                if conf is None:
                    continue
                if not (0.0 <= conf <= 1.0):
                    violations.append((rec.target_id, conf))
    finally:
        video.release()

    assert not violations, f"Confidence out of range: {violations[:10]}"


