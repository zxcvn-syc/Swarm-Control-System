"""YOLO inference speed and accuracy tests using real cvtrack + test videos.

These tests run the actual ``CvtrackRunner`` pipeline (no ROS2, no mocks) on
the synthetic test videos so we can measure true per-frame latency and
verify the output shape without any abstraction leakage.

Tests
-----
- test_average_fps_above_3hz_on_synthetic_video   — ≥ 3 Hz on CPU
- test_bbox_coordinates_within_frame_bounds        — all bboxes are in-frame
- test_detections_found_on_multi_target_video     — at least 1 track per frame
- test_frame_timestamps_are_monotonic            — no time travel
- test_predicted_trajectory_length                — 5 prediction steps
- test_motion_mode_is_valid                     — 0-3 range
- test_speed_is_non_negative                     — physical sanity
"""

