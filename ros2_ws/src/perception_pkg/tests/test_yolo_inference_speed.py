@pytest.fixture(scope="module")
def runner():
    """Create a CvtrackRunner with MOG2 (CPU, no GPU needed) for synthetic videos.

    MOG2 is used instead of YOLO because:
    1. No GPU / YOLO weights are required — tests are fully self-contained.
    2. MOG2 produces stable multi-target detections on the synthetic videos.
    3. The latency of MOG2 is similar to YOLO on CPU for small frames.

    The fps is estimated from the video header; dt is derived from it.
    """
    overrides = {
        "detector": {
            "backend": "auto",   # auto → MOG2 on synthetic content
            "device": "cpu",
            "imgsz": 320,
            "conf": 0.15,
            "classes": [],
            "min_box_area": 50.0,
            "min_conf": 0.0,
            "nms_iou": 0.5,
        },
        "tracker": {
            "kind": "deepsort_cascade",
            "max_age": 30,
            "n_init": 3,
            "iou_thresh": 0.30,
            "high_conf": 0.35,
            "new_track_conf": 0.20,
            "lost_relink_frames": 30,
            "stationary_prune": True,
        },
        "appearance": {
            "enabled": False,
        },
    }
    return CvtrackRunner.from_overrides(preset=None, overrides=overrides, fps=20.0)


# ---------------------------------------------------------------------------
# 1. FPS test
# ---------------------------------------------------------------------------

def test_average_fps_above_3hz_on_synthetic_video(runner):
    """Average frame rate must be ≥ 3 Hz on CPU with MOG2 + DeepSORT.

    We process up to _MAX_FRAMES_PER_TEST frames, skipping the first 5 warm-up
    frames so the detector background model stabilises.
    """
    video = _open_video(_synthetic_multi())
    n_warmup = 5
    latencies: list[float] = []

    try:
        for i in range(n_warmup + _MAX_FRAMES_PER_TEST):
            ok, frame = video.read()
            if not ok:
                break
            if i < n_warmup:
                # Warm-up: run detection to initialise the background model.
                runner.step(frame)
                continue
            t0 = time.monotonic()
            runner.step(frame)
            dt = time.monotonic() - t0
            latencies.append(dt)
    finally:
        video.release()

    assert latencies, "No frames were processed (video may be empty)"
    avg_latency = sum(latencies) / len(latencies)
    avg_fps = 1.0 / avg_latency

    print(f"\n  Processed {len(latencies)} frames")
    print(f"  Average latency: {avg_latency*1000:.1f} ms/frame")
    print(f"  Average FPS: {avg_fps:.2f} Hz")
    print(f"  Min latency: {min(latencies)*1000:.1f} ms")
    print(f"  Max latency: {max(latencies)*1000:.1f} ms")

    assert avg_fps >= _MIN_FPS, (
        f"Average FPS {avg_fps:.2f} Hz is below the {_MIN_FPS} Hz threshold. "
        f"Latency: {avg_latency*1000:.1f} ms/frame."
    )


# ---------------------------------------------------------------------------
# 2. Bounding-box in-frame sanity
# ---------------------------------------------------------------------------

def test_bbox_coordinates_within_frame_bounds(runner):
    """All bounding-box coordinates must be inside the frame dimensions."""
    video = _open_video(_synthetic_multi())
    violations: list[tuple] = []

    try:
        for _ in range(_MAX_FRAMES_PER_TEST):
            ok, frame = video.read()
            if not ok:
                break
            records = runner.step_records(frame)
            H, W = frame.shape[:2]
            for rec in records:
                # Build a rough bbox from centroid ± 20 px if no box attr.
                if hasattr(rec, "box") and rec.box is not None:
                    x1, y1, x2, y2 = rec.box.x1, rec.box.y1, rec.box.x2, rec.box.y2
                else:
                    half = 20.0
                    x1 = rec.x - half
                    y1 = rec.y - half
                    x2 = rec.x + half
                    y2 = rec.y + half
                if x1 < 0 or y1 < 0 or x2 > W or y2 > H or x1 > x2 or y1 > y2:
                    violations.append(
                        (rec.target_id, (x1, y1, x2, y2), f"frame={H}x{W}")
                    )
    finally:
        video.release()

    assert not violations, (
        f"Found {len(violations)} out-of-bounds bbox(es): {violations[:5]}"
    )


# ---------------------------------------------------------------------------
# 3. Multi-target detection
# ---------------------------------------------------------------------------

def test_detections_found_on_multi_target_video(runner):
    """On a multi-target video we should see ≥ 1 confirmed track on most frames."""
    video = _open_video(_synthetic_multi())
    frames_with_tracks: int = 0
    total_frames: int = 0

    try:
        for _ in range(n_warmup := 5 + _MAX_FRAMES_PER_TEST):
            ok, frame = video.read()
            if not ok:
                break
            records = runner.step_records(frame)
            if len(records) > 0:
                frames_with_tracks += 1
            total_frames += 1
    finally:
        video.release()

    detection_rate = frames_with_tracks / max(total_frames, 1)
    print(f"\n  Total frames: {total_frames}, frames with tracks: {frames_with_tracks}")
    print(f"  Detection rate: {detection_rate:.1%}")

    # MOG2 on synthetic content should produce detections on most frames.
    assert frames_with_tracks > 0, (
        "No frames had any confirmed tracks — detector may not be working."
    )
    assert detection_rate >= 0.50, (
        f"Detection rate {detection_rate:.1%} is too low "
        "(expected ≥ 50% on synthetic multi-target video)."
    )


# ---------------------------------------------------------------------------
# 4. Timestamp monotonicity (simulated time logic)
# ---------------------------------------------------------------------------

def test_frame_timestamps_are_monotonic(runner):
    """frame_idx must be strictly increasing across consecutive publish ticks.

    We verify this by tracking the internal frame counter behaviour.
    The runner's step() processes frames sequentially; the node increments
    frame_idx on every _publish_tick.  Here we just verify step() itself
    doesn't throw on sequential frames.
    """
    video = _open_video(_synthetic_multi())
    frame_idx = 0

    try:
        for _ in range(_MAX_FRAMES_PER_TEST):
            ok, frame = video.read()
            if not ok:
                break
            records = runner.step_records(frame)
            # Sequential calls must produce consistent results.
            assert isinstance(records, list)
            frame_idx += 1
    finally:
        video.release()

    assert frame_idx >= 10, "Not enough frames processed to validate monotonicity"


